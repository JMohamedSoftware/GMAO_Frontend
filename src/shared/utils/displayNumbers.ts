/**
 * Per-tenant display number utilities.
 *
 * Each company has its own independent numbering sequence starting at 001.
 * Display numbers are derived from the sorted position of each item within
 * the CURRENT tenant's list — no global DB ids are exposed to the user.
 *
 * Format:
 *   DI-001  → Incidents (Pannes / Déclarations)
 *   OT-001  → Work Orders (Correctifs / Préventifs)  — uses backend numeroOT when available
 *   EQ-001  → Equipment codes                         — uses backend code when available
 *   PP-001  → Plans Préventifs
 */

import type { Incident, WorkOrder, Equipment } from '@/shared/types/gmao';
import type { PlanPreventif } from '@/features/company/preventive/types/preventive.types';

const pad = (n: number) => String(n).padStart(3, '0');

/** DI-001 … DI-999 — position in tenant's incident list (sorted by numeric id asc) */
export const incidentDisplayNum = (inc: Incident, allIncidents: Incident[]): string => {
  const sorted = [...allIncidents].sort((a, b) => Number(a.id) - Number(b.id));
  const pos = sorted.findIndex(i => i.id === inc.id);
  return `DI-${pad(pos >= 0 ? pos + 1 : 1)}`;
};

/**
 * OT-001 … — prefers the per-company numeroOT generated by the backend
 * (e.g. "OT-2026-S3-001"). Falls back to position in sorted list.
 */
export const otDisplayNum = (ot: WorkOrder, allOts: WorkOrder[]): string => {
  if (ot.numeroOT && ot.numeroOT.trim() !== '') return ot.numeroOT;
  const sorted = [...allOts].sort((a, b) => Number(a.id) - Number(b.id));
  const pos = sorted.findIndex(o => o.id === ot.id);
  return `OT-${pad(pos >= 0 ? pos + 1 : 1)}`;
};

/**
 * EQ-001 … — prefers the code field already returned by the backend
 * (which is per-company). Falls back to position in sorted list.
 */
export const equipmentDisplayCode = (eq: Equipment, allEquipments: Equipment[]): string => {
  if (eq.code && eq.code.trim() !== '') return eq.code;
  const sorted = [...allEquipments].sort((a, b) => Number(a.id) - Number(b.id));
  const pos = sorted.findIndex(e => e.id === eq.id);
  return `EQ-${pad(pos >= 0 ? pos + 1 : 1)}`;
};

/** PP-001 … — position in tenant's preventive plan list (sorted by id asc) */
export const planDisplayNum = (plan: PlanPreventif, allPlans: PlanPreventif[]): string => {
  const sorted = [...allPlans].sort((a, b) => a.id - b.id);
  const pos = sorted.findIndex(p => p.id === plan.id);
  return `PP-${pad(pos >= 0 ? pos + 1 : 1)}`;
};
